### Q9:- Given 2 fractions, find the sum of those 2 fractions.Take the numerator and denominator values of 
         # the fractions from the user.

s1= int(input("Enter numerator:"))
s2 = int(input("Enter denominator:"))


s3 = int(input("Enter second numerator:"))
s4 = int(input("Enter second denominator:"))

nume = (s1*s4) + (s2*s3)
deno = s2*s4

print("The final answer is",nume,"/",deno)

